import re
import sqlite3

from Configuration.config import MAX_ROWS


def validate_sql_query(sql_statement:str)->tuple[bool,str]:
    # FIX: always return (bool, message). Two branches returned a bare `False`,
    # which crashed execute_sql_nodes with "'bool' object is not subscriptable".
    sql_statement=sql_statement.strip().rstrip(";").strip()
    if not sql_statement:
        return False, "Empty SQL query"
    first_word=sql_statement.split(None,1)[0].upper()
    if first_word not in {"SELECT","WITH"}:
        return False , "Only Queries are allowed"
    if ";" in sql_statement:
        return False, "Only one SQL statement is allowed"
    return True,""

def execute_query(uri,sql):
    conn=None
    try:
        conn=sqlite3.connect(uri,uri=True,timeout=5)
        conn.execute("PRAGMA query_only = ON")
        allowed_actions={
            sqlite3.SQLITE_SELECT,
            sqlite3.SQLITE_READ,
            sqlite3.SQLITE_FUNCTION
        }
        #Checks if your version of Python supports recursive queries (common in advanced CTEs) and adds that permission to your allowed list if available.
        if hasattr(sqlite3,"SQLITE_RECURSIVE"):
            allowed_actions.add(sqlite3.SQLITE_RECURSIVE)

        #Defines a custom callback function (authorize) that SQLite calls every single time it is about to perform an internal action.
        #If the action is in our allowed_actions list, it returns sqlite3.SQLITE_OK (allow it). Otherwise, it returns sqlite3.SQLITE_DENY (block it immediately).
        #conn.set_authorizer(authorize) registers this security guard function onto the database connection.
        def authorize(action,arg1,arg2,database,trigger):
            if action in allowed_actions:
                return sqlite3.SQLITE_OK
            return sqlite3.SQLITE_DENY

        conn.set_authorizer(authorize)

        cursor=conn.execute(sql.strip().rstrip(";"))

        #Extracts the column names from the query results (e.g., product_name, revenue) so you know what data fields were returned.Python
        columns=[
            description[0]
            for description in (cursor.description or [])
        ]
        #Fetches up to MAX_ROWS+1 rows from the result set. Fetching one extra row is a clever trick to check if the query result exceeded your safety limit.
        rows=cursor.fetchmany(MAX_ROWS+1)

        #If the query returned more than MAX_ROWS rows, it slices the list down. This prevents a poorly written query from crashing your application or overwhelming the LLM with thousands of lines of data.
        if len(rows)>MAX_ROWS:
            rows=rows[:MAX_ROWS]

        #Packages the column names and row values into a clean Python dictionary, converts it to a string for the graph state, and clears out any previous error message because the query succeeded
        result={
            "columns":columns,
            "rows":[list(row) for row in rows],
        }

        return {
            "query_result":str(result),
            "error":"",
        }
    ##Catches any errors raised by SQLite (such as a syntax error or a typo in a column name generated by Gemma).
    #Returns an empty query_result and captures the error message (truncated to 1,000 characters max).
    except sqlite3.Error as exc:
        return {
            "query_result":"",
            "error":str(exc)[:1000]
        }
    finally:
        # FIX: `with sqlite3.connect(...)` commits/rolls back but never closes the connection.
        if conn is not None:
            conn.close()


def clean_sql_output(llm_output:str)->str:
    """
    Pull the SQL out of the LLM reply.
    Replaces the fence-stripping code that was duplicated in create_sql and generate_sql_node,
    and also handles replies like "Here is the SQL query: SELECT ..." or text after the query,
    which small models often produce and which used to fail validation every time.
    """
    text=llm_output.strip()
    # 1. Prefer the content of a ```sql ... ``` block if there is one
    block=re.search(r"```(?:sql|sqlite)?\s*\n?(.*?)(?:```|$)",text,re.DOTALL|re.IGNORECASE)
    if block:
        text=block.group(1)
    # 2. Start at the first SELECT/WITH at the beginning of a line (or anywhere as a fallback)
    start=re.search(r"^\s*(SELECT|WITH)\b",text,re.IGNORECASE|re.MULTILINE) or re.search(r"\b(SELECT|WITH)\b",text)
    if not start:
        return ""
    text=text[start.start(1):]
    # 3. Stop at the end of the first statement
    text=text.split(";",1)[0]
    return text.strip()


def create_sql(llm,prompt,schema,state):
    sql_query = clean_sql_output(llm.invoke(prompt))
    return {
             "schema": schema,
             "sql_query": sql_query,
             "error": "",
             "attempts": state.get("attempts", 0) + 1,
         }

# This was an exact copy of create_sql; kept as an alias so nothing that imports it breaks.
generate_sql_node = create_sql

def read_table_and_columns(DB_PATH):

    with sqlite3.connect(DB_PATH)as conn:
             rows = conn.execute("""
                     Select name,sql
                     from sqlite_master
                     where type = 'table'
                     and name not like 'sqlite_%'
                     order by name
                     """).fetchall()
    return "\n\n".join(
             f"Table :{name}\n{definition}"
             for name , definition in rows
         )
